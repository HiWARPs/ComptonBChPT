"""Step 8: v1 -> v2 comparison of all headline numbers -> results/v1_v2_comparison.md (+ .tex).
v1 = archived results (results_v1/, code work/code, forward points <= 135 MeV);
v2 = current results (results/, code work/code_v2 with vertex corrections + physical masses, forward points <= 145 MeV)."""
import os, sys, json
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lib'))
import numpy as np
from common import FITS

R1, R2 = os.path.join(FITS, 'results_v1'), os.path.join(FITS, 'results')
L1, L2 = json.load(open(os.path.join(R1, 'fits_L.json'))), json.load(open(os.path.join(R2, 'fits_L.json')))
D1, D2 = json.load(open(os.path.join(R1, 'delta_region.json'))), json.load(open(os.path.join(R2, 'delta_region.json')))
B1, B2 = json.load(open(os.path.join(R1, 'error_budget.json'))), json.load(open(os.path.join(R2, 'error_budget.json')))
MD, TX = [], []


def pe(v, e):
    return '%.2f(%d)' % (v, round(100 * e)) if e < 1 else '%.2f(%.2f)' % (v, e)


def ab(r):
    return pe(r['P'][0], r['dP'][0]), pe(r['P'][1], r['dP'][1])


rows = []


def add(label, k1, k2=None, extra=None):
    k2 = k2 or k1
    if k1 not in L1 or k2 not in L2:
        return
    a, b = L1[k1], L2[k2]
    rows.append((label, '%s / %s' % ab(a), '%.1f/%d' % (a['chi2'], a['dof']), '%s / %s' % ab(b), '%.1f/%d' % (b['chi2'], b['dof']),
                 '%+.2f / %+.2f' % (b['P'][0] - a['P'][0], b['P'][1] - a['P'][1])))


add('MAIN: F2 (fwd points, nuisances) + trunc. cov. [v1: fwd ≤ 135, v2: fwd ≤ 145 MeV]', 'F2_d_all_thB')
add('F2, fwd ≤ 135 MeV in both, + trunc. cov.', 'F2_d_all_thB', 'F2_d_fwd135_thB')
add('F2, fwd ≤ 150 MeV, + trunc. cov.', 'F2_d_fwd150_thB')
add('F2, fwd uncorrelated + trunc. cov.', 'F2_d_fwd_uncorr_thB')
add('F2, no trunc. cov.', 'F2_d_all')
add('F2, no trunc. cov., fwd ≤ 135 in both', 'F2_d_all', 'F2_d_fwd135')
add('F1 (Baldin 14.0(2)) + trunc. cov.', 'F1_d_all_thB')
add('F1, no trunc. cov.', 'F1_d_all')
add('F3: F2 + γM1M1, γE1E1 free + trunc.', 'F3_d_all_thB')
add('F2 + γπ free + trunc.', 'F2pi_d_all_thB')
for v, l in [('a_pre2015', '(a) pre-2015'), ('b_A2only', '(b) A2 only'), ('c_HIGSonly', '(c) HIγS only'), ('e_noTAPS', '(e) − TAPS'),
             ('f_GMPFpruned', '(f) GMPF pruning'), ('g_A2perbeam', '(g) A2 per beamtime'), ('i_noHIGS', '(i) − HIγS')]:
    add('main config. %s' % l, 'F2_%s_thB' % v)
add('main config. (h) 3σ', 'F2_h_3sigma_thBmain')
add('main config. F4 (E ≤ 170)', 'F2_F4_all_thB')
add('F1 − HIγS + trunc.', 'F1_i_noHIGS_thB')
add('F1 − HIγS, no trunc.', 'F1_i_noHIGS')
add('Mornacchi benchmark [thesis 10.66(15)(41), 3.40(20)(22), 154.6/187]', 'bench_Mornacchi')
add('LM14-type [10.6(5), 3.2(5)]', 'LM14_type')
add('TAPS only (Baldin) + trunc.', 'F1_TAPSonly_thB')
add('A2 dσ only (Baldin) + trunc.', 'F1_A2_CSonly_thB')

MD += ['# v1 → v2 comparison of the headline numbers (generated by scripts/s08_compare_v1_v2.py)', '',
       'v1: work/code (no γNΔ vertex corrections, single charged-pion mass in the loops, observable-level 0° extrapolation);',
       'v2: work/code_v2 MAIN = dvertex=t, pimassphys=t, nmassphys=t, consts=LMP15 (bug fixes, exact 0°/180°, physical cusps).',
       'Database, fit machinery and truncation scheme identical; v2 main includes the 145 MeV forward points.', '',
       '## Region L fits (α, β in 1e-4 fm³)', '',
       '| fit | v1: α / β | v1 χ²/dof | v2: α / β | v2 χ²/dof | Δ(v2−v1) α / β |', '|---|---|---|---|---|---|']
for r in rows:
    MD.append('| %s | ' % r[0] + ' | '.join(r[1:]) + ' |')

# derived quantities of the main fit
m1, m2 = L1['F2_d_all_thB'], L2['F2_d_all_thB']
MD += ['', '## Main fit: derived quantities', '', '| quantity | v1 | v2 |', '|---|---|---|',
       '| α+β | %s | %s |' % (pe(m1['apb'], m1['dapb']), pe(m2['apb'], m2['dapb'])),
       '| α−β | %s | %s |' % (pe(m1['amb'], m1['damb']), pe(m2['amb'], m2['damb'])),
       '| ρ(α,β) | %.2f | %.2f |' % (m1['rho_ab'], m2['rho_ab']),
       '| γ0 (fixed NNLO input) | %.3f | %.3f |' % (m1['g0'], m2['g0']),
       '| γπ (fixed NNLO input) | %.2f | %.2f |' % (m1['gpi'], m2['gpi']),
       '| nuisance λ_f | %.2f(%.2f) | %.2f(%.2f) |' % (m1['lam_shift'][0], m1['lam_shift_err'][0], m2['lam_shift'][0], m2['lam_shift_err'][0]),
       '| nuisance λ_g | %.2f(%.2f) | %.2f(%.2f) |' % (m1['lam_shift'][1], m1['lam_shift_err'][1], m2['lam_shift'][1], m2['lam_shift_err'][1]),
       '| N points (fwd) | %d | %d |' % (m1['N'], m2['N'])]
f1, f2 = L1['F3_d_all_thB'], L2['F3_d_all_thB']
MD += ['| F3: γM1M1 | %s | %s |' % (pe(f1['P'][3], f1['dP'][3]), pe(f2['P'][3], f2['dP'][3])),
       '| F3: γE1E1 | %s | %s |' % (pe(f1['P'][2], f1['dP'][2]), pe(f2['P'][2], f2['dP'][2])),
       '| F3: γ0 | %s | %s |' % (pe(f1['g0'], f1['dg0']), pe(f2['g0'], f2['dg0'])),
       '| F3: γπ | %s | %s |' % (pe(f1['gpi'], f1['dgpi']), pe(f2['gpi'], f2['dgpi']))]
h1, h2 = L1['HIGS_test'], L2['HIGS_test']
for k in ['F2_thB', 'F2', 'F1_thB', 'F1']:
    MD.append('| PG test HIγS vs rest, %s: χ²_PG (p) | %.2f (%.3f) | %.2f (%.3f) |' % (k, h1[k]['PG'], h1[k]['PG_p'], h2[k]['PG'], h2[k]['PG_p']))
MD.append('| χ² of the 16 HIγS points predicted by the no-HIγS main fit (n=1) | %.1f | %.1f |' % (h1['F2_thB']['chi2_HIGS_pred_n1'], h2['F2_thB']['chi2_HIGS_pred_n1']))

# error budget
MD += ['', '## Error budget of the main fit', '', '| source | v1 δα | v1 δβ | v2 δα | v2 δβ |', '|---|---|---|---|---|']
c1 = {k: v for k, v in B1['F2']['comps']}
for k, v in B2['F2']['comps']:
    k1 = k
    if k not in c1:   # renamed items
        k1 = {'constants → PDG24 (gA, fπ, masses, hA refit)': 'constants gA, fπ → PDG',
              'hA ± (Γ_Δ = 114–120 MeV: hA = 2.84–2.91)': 'hA (Δ width), est.'}.get(k, k)
    a = c1.get(k1, [np.nan, np.nan])
    MD.append('| %s | %.2f | %.2f | %.2f | %.2f |' % (k, a[0], a[1], v[0], v[1]))

# energy scan
MD += ['', '## Upper-energy-cut scan: β (does the drift between 120 and 150 MeV shrink with the physical cusps?)', '',
       '| E_max | F1 no trunc. v1 | v2 | F2 + trunc. v1 | v2 |', '|---|---|---|---|---|']
for E in [90, 100, 110, 120, 130, 140, 150, 160, 170]:
    a1, a2 = L1['scan_F1_noth_E%d' % E], L2['scan_F1_noth_E%d' % E]
    b1, b2 = L1['scan_F2_thB_E%d' % E], L2['scan_F2_thB_E%d' % E]
    MD.append('| %d | %s | %s | %s | %s |' % (E, pe(a1['P'][1], a1['dP'][1]), pe(a2['P'][1], a2['dP'][1]), pe(b1['P'][1], b1['dP'][1]),
                                              pe(b2['P'][1], b2['dP'][1])))

# Delta region
MD += ['', '## Δ region: χ²/N per data set of the parameter-free NNLO prediction (normalisation fitted with penalty)', '',
       '| set | N | v1 χ²/N | v2 no vertex χ²/N | v2 χ²/N | v1 χ² (n=1) | v2 no vertex χ² (n=1) | v2 χ² (n=1) |', '|---|---|---|---|---|---|---|---|']
t1 = {r['set']: r for r in D1['chi2_NNLO']}; t2 = {r['set']: r for r in D2['chi2_NNLO']}
t2n = {r['set']: r for r in D2.get('chi2_NNLO_novtx', [])}
for k in t1:
    MD.append('| %s | %d | %.2f | %s | %.2f | %.1f | %s | %.1f |' % (k, t1[k]['N'], t1[k]['chi2N'], ('%.2f' % t2n[k]['chi2N']) if k in t2n else '–',
              t2[k]['chi2N'], t1[k]['chi2_n1'], ('%.1f' % t2n[k]['chi2_n1']) if k in t2n else '–', t2[k]['chi2_n1']))
MD += ['', '## γNΔ coupling gM fitted to single Δ-region data sets (spin pols NNLO, α, β constrained; prior 2.97(50))', '',
       '| data | v1 | v2 without vertex corr. | v2 with vertex corr. |', '|---|---|---|---|']
for k, l in [('gM_only_A2asym', 'A2 Σ2x + Σ2z'), ('gM_only_LEGS_S3', 'LEGS Σ3 (< 2π)'), ('gM_only_MAMIcs', 'MAMI dσ'),
             ('gM_only_LEGScs', 'LEGS dσ'), ('gM_only_Hallin', 'Hallin dσ')]:
    g1 = D1[k]['extra']['gM']; g2 = D2[k]['extra']['gM']; g2n = D2.get(k + '_novtx', {}).get('extra', {}).get('gM')
    MD.append('| %s | %.3f(%d) | %s | %.3f(%d) |' % (l, g1[0], round(1000 * g1[1]), ('%.3f(%d)' % (g2n[0], round(1000 * g2n[1]))) if g2n else '–',
                                                    g2[0], round(1000 * g2[1])))
vals = lambda D, ks: [D[k]['extra']['gM'][0] for k in ks if k in D]
ks = ['gM_only_A2asym', 'gM_only_LEGS_S3', 'gM_only_MAMIcs', 'gM_only_LEGScs', 'gM_only_Hallin']
for lab, D, kk in [('v1', D1, ks), ('v2 no vertex', D2, [k + '_novtx' for k in ks]), ('v2', D2, ks)]:
    v = vals(D, kk)
    if v:
        MD.append('')
        MD.append('Spread (max − min) of the single-set gM, %s: %.2f (range %.2f–%.2f)' % (lab, max(v) - min(v), min(v), max(v)))
MD += ['', '## Δ region: spin-polarisability fit (A2 Σ2x+Σ2z + LEGS Σ3 < 2π, γπ = 8.0(1.8), γ0 = −0.929(105))', '',
       '| | γE1E1 | γM1M1 | γE1M2 | γM1E2 | γπ | χ²/dof |', '|---|---|---|---|---|---|---|']
for lab, D, k in [('v1', D1, 'S_A2_LEGS_gpi'), ('v2 without vertex corr.', D2, 'S_A2_LEGS_gpi_novtx'), ('v2 (vertex corr.)', D2, 'S_A2_LEGS_gpi'),
                  ('v1, no γπ constraint', D1, 'S_A2_LEGS'), ('v2, no γπ constraint', D2, 'S_A2_LEGS'),
                  ('v1, A2 only (γE1E1, γM1M1)', D1, 'S_A2_2free'), ('v2, A2 only (γE1E1, γM1M1)', D2, 'S_A2_2free')]:
    if k not in D:
        continue
    r = D[k]
    MD.append('| %s | %s | %s | %s | %s | %s | %.1f/%d |' % (lab, pe(r['P'][2], r['dP'][2]), pe(r['P'][3], r['dP'][3]),
              pe(r['P'][4], r['dP'][4]) if r['dP'][4] > 0 else '%.2f*' % r['P'][4], pe(r['P'][5], r['dP'][5]) if r['dP'][5] > 0 else '%.2f*' % r['P'][5],
              pe(r['gpi'], r['dgpi']), r['chi2'], r['dof']))

open(os.path.join(R2, 'v1_v2_comparison.md'), 'w').write('\n'.join(MD) + '\n')
print('\n'.join(MD))
