"""Step 7b: the error-budget table of Appendix D (paper Table 'budget') from results/error_budget.json.

Rows: the four components of the fit uncertainty (statistical, normalizations, forward points or Baldin sum rule,
truncation) and their subtotal; the six systematic sources of Section IV B ('constants' and 'hA' of the JSON merged
in quadrature into the single row 'parameters of Table params'; the forward-point correlation model does not apply
to the Baldin fit) and their subtotal; the total.  Columns: NNLO fit (JSON entry F2) and Baldin fit (entry F1).
Checks printed: the fit subtotal against the quadrature sum of its four rows, and TOTAL^2 = fit^2 + syst^2.
Writes results/error_budget_table.tex (complete revtex table environment, \\tablab{budget}).  Run after s07."""
import os, sys, json
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lib'))
from common import RES  # noqa: E402

EB = json.load(open(os.path.join(RES, 'error_budget.json')))


def rows_of(kind):
    comps = {k: np.array(v) for k, v in EB[kind]['comps']}
    keys = list(comps)
    fit_rows = keys[:4]                                         # stat, norm, forward/Baldin, truncation
    fit = comps['= total fit error']
    syst_keys = [k for k in keys if k not in fit_rows and k not in ('= total fit error', '**TOTAL**')]
    const = [k for k in syst_keys if k.startswith('constants')][0]
    hA = [k for k in syst_keys if k.startswith('hA')][0]
    params = np.sqrt(comps[const] ** 2 + comps[hA] ** 2)
    fwdmodel = [comps[k] for k in syst_keys if k.startswith('forward-error model')]
    syst = np.sqrt(sum(comps[k] ** 2 for k in syst_keys))
    total = comps['**TOTAL**']
    out = dict(P=np.array(EB[kind]['P']), stat=comps[fit_rows[0]], norm=comps[fit_rows[1]], con=comps[fit_rows[2]],
               trunc=comps[fit_rows[3]], fit=fit, fit_quad=np.sqrt(sum(comps[k] ** 2 for k in fit_rows)),
               tmodel=comps[[k for k in syst_keys if k.startswith('truncation-model')][0]],
               dbs=comps[[k for k in syst_keys if k.startswith('database')][0]],
               spin=comps[[k for k in syst_keys if k.startswith('spin')][0]],
               gM=comps[[k for k in syst_keys if 'gM' in k][0]], params=params,
               fwdmodel=fwdmodel[0] if fwdmodel else None, syst=syst, total=total,
               total_check=np.sqrt(fit ** 2 + syst ** 2))
    return out


F2, F1 = rows_of('F2'), rows_of('F1')
for name, r in (('F2 (NNLO fit)', F2), ('F1 (Baldin fit)', F1)):
    print('%s: fit subtotal (JSON) = %.4f %.4f, quadrature of the four rows = %.4f %.4f, diff = %+.4f %+.4f'
          % (name, *r['fit'], *r['fit_quad'], *(r['fit_quad'] - r['fit'])))
    print('   syst (quadrature of the systematic rows) = %.4f %.4f;  sqrt(fit^2+syst^2) = %.4f %.4f;  JSON TOTAL = %.4f %.4f;  diff = %.1e %.1e'
          % (*r['syst'], *r['total_check'], *r['total'], *np.abs(r['total_check'] - r['total'])))
    assert np.allclose(r['total_check'], r['total'], atol=1e-9), 'TOTAL^2 = fit^2 + syst^2 violated'


def f2(x):
    return '%.2f' % x


def row(label, key):
    a, b = F2[key], F1[key]
    sb = (f2(b[0]), f2(b[1])) if b is not None else ('--', '--')
    return '%s & %s & %s & %s & %s \\\\' % (label, f2(a[0]), f2(a[1]), *sb)


