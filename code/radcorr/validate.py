os.makedirs(OUT, exist_ok=True)
L = []
me, Mp = rc.M_E, rc.M_P


def p(s=''):
    print(s); L.append(s)


p('# Validation of `radcorr.py` (generated by validate.py)')
p()
p('## 1. Born amplitudes vs Klein-Nishina (lab, nb/sr), M = M_p, omega = 100 MeV')
p('| theta_lab | KN | from helicity amplitudes | Sigma_3 KN (lin. pol.) | Sigma_3 from amplitudes |')
p('|---|---|---|---|---|')
for th in [0.001, 30, 45, 90, 135, 150, 179.999]:
    k = rc.kin(100, th); om, omp = float(k['omega']), float(k['omp']); s2 = np.sin(np.radians(th)) ** 2
    p('| %.3f | %.7f | %.7f | %.7f | %.7f |' % (th, rc.klein_nishina_lab(100, th), rc.born_cs_lab(100, th),
                                               -s2 / (omp / om + om / omp - s2), rc.sigma3(100, th, order=0)))
p()
p('## 2. IR finiteness: delta_V(lambda) + delta_soft(lambda; Delta E) (lab cut), M = M_p')
p('| omega | theta | Delta E | lambda [MeV] | delta_V | delta_soft | sum |')
p('|---|---|---|---|---|---|---|')
for (w, th, dE) in [(100, 90, 3.0), (150, 170, 1.0), (60, 30, 10.0)]:
    for lam in [1e-6, 1e-2, 1.0, 1e3]:
        dv = rc.delta_virtual(w, th, lam=lam); ds = rc.soft_lab(w, th, dE, lam=lam)
        p('| %g | %g | %g | %g | %.8e | %.8e | %.10e |' % (w, th, dE, lam, dv, ds, dv + ds))
p()
p('## 3. Thirring: delta -> 0 for omega -> 0 (theta = 90 deg, Delta E = 3% of omega; also 45 and 135 deg)')
p('| omega [MeV] | delta(45) | delta(90) | delta(135) | delta(90)/(omega/M)^2 |')
p('|---|---|---|---|---|')
for w in [0.01, 0.1, 1, 3, 10, 30, 60, 100, 150]:
    d45, d90, d135 = [rc.delta(w, th, 0.03 * w) for th in (45, 90, 135)]
    p('| %g | %.3e | %.3e | %.3e | %.4e |' % (w, d45, d90, d135, d90 / (w / Mp) ** 2))
p()
p('## 4. Low-energy limit per helicity amplitude: M1/M0 vs delta_low of Denner-Dittmaier Eq. (3.6) (lambda = M)')
p('(residual (M1/M0 - delta_low)/beta should be O(beta))')
p('| omega | beta | theta_cm | amplitude | M1/M0 | delta_low (DD) | (M1/M0 - delta_low)/beta |')
p('|---|---|---|---|---|---|---|')
names = ['(++++)', '(+-+-)', '(+--+)', '(+---)', '(+++-)', '(++--)']
for w in [0.5, 5.0, 50.0]:
    for th in [60.0, 120.0]:
        k = rc.kin(w, th)
        A = rc.born_amps(k['s'], k['t'], k['u'], k['M']); B = rc.loop_amps(k['s'], k['t'], k['u'], k['M'], k['M'])
        thcm = float(mp.acos(k['cos_cm']) * 180 / mp.pi); beta = float(k['beta'])
        dl = rc.delta_low_DD(thcm, beta)
        for i in range(6):
            rat = float(B[i] / A[i])
            p('| %g | %.5f | %.2f | %s | %.4e | %.4e | %.2e |' % (w, beta, thcm, names[i], rat, dl[i], (rat - dl[i]) / beta))
p()
p('## 5. Electron (M = m_e): virtual part vs Brown-Feynman (lambda = m_e, i.e. their ln(lambda) = 0)')
p('BF Eq. (49) [theta_lab = 0, extreme-relativistic]: -(alpha/pi) b(0)/U, b(0) = -ln(tau)(1+ln(tau)) + 1.355, U = 2, tau = 2 omega/m.')
p('BF Eq. (51) [theta_cm = 90 deg, extreme-relativistic]: -(alpha/pi)(2y^2 - 3y - 2.29), 4 sinh^2 y = tau = omega_2 2/m with kappa = -2 tau (i.e. tau = omega/m).')
p('(the printed BF Table II deviates from Eqs. (49),(51) themselves by up to 0.1% absolute at some entries; we compare with the formulae)')
p('| omega [MeV] | delta_V(0 deg) exact | BF (49) | delta_V(90 cm) exact | BF (51) | theta_lab(90 cm) |')
p('|---|---|---|---|---|---|')
for w in [17.6, 50., 150., 300., 1000., 3000.]:
    thl90 = rc.theta_lab_of_cm(w, 90.0, me)
    d0 = rc.delta_virtual(w, 1e-4, me, lam=me); d90 = rc.delta_virtual(w, thl90, me, lam=me)
    tau = 2 * w / me; b0 = -mp.log(tau) * (1 + mp.log(tau)) + 1.355
    tau2 = w / me; y = mp.asinh(mp.sqrt(tau2 / 4)); b90 = 2 * y ** 2 - 3 * y - 2.29
    p('| %g | %.3f%% | %.3f%% | %.3f%% | %.3f%% | %.3f |' % (w, 100 * d0, 100 * float(-rc.ALPHA / mp.pi * b0 / 2),
                                                           100 * d90, 100 * float(-rc.ALPHA / mp.pi * b90), thl90))
p()
p('**Direct comparison with the exact Brown-Feynman closed form, Eq. (30): see results/check_bf30.md (check_bf30.py):**')
p('the two independent closed forms (BF 1952 unpolarised trace result; DD 1999 helicity amplitudes) agree to ~1e-18 at all')
p('masses, energies, angles and photon masses tested.')
p()
p("BF Fig. 5: delta' = -U^(1)/U - 2(1 - 2y coth 2y) ln(lambda) = delta_V(lambda = m)/(alpha/pi) vs lab angle, their hand-computed curves.")
p('Values read off the figure (+-0.15): 17.6 MeV: 8.3 (0 deg), 2.4 (15), ~0.1 (45), ~0.6 (70), 3.2 (100), 4.4 (160), 4.5 (180);')
p('2.62 MeV: 3.75 (0), 3.3 (20), 0.55 (45), 1.5 (70), 3.0 (100), 4.3 (150), 4.5 (180).')
p('Our values agree with the figure at forward and backward angles but not in the 30-70 deg dip; since our evaluation of')
p('their own Eq. (30) coincides with ours (check_bf30.md), and their printed Table II deviates from their Eqs. (49),(51) by up')
p('to 0.1% absolute, the dips must be artefacts of the 1952 numerical evaluation (or of the figure), not of the formulae.')
p("| omega | angle | delta'(ours) |")
p('|---|---|---|')
for w, angs in [(17.6, [0.001, 15, 45, 70, 100, 160, 179.999]), (2.62, [0.001, 20, 45, 70, 100, 150, 179.999])]:
    for a in angs:
        p('| %g | %g | %.2f |' % (w, a, rc.delta_virtual(w, a, me, lam=me) / (rc.ALPHA / np.pi)))
p()
p('## 6. Non-relativistic limit, BF Eqs. (55)-(57): U^(1) = -(4/3) w^2 (1-cos) U ln(lambda) + 4 w^2 ln(w) f(phi) + O(w^2),')
p('f(phi) = 1 + cos(phi) + cos^2(phi) - cos^3(phi)/3  (their Fig. 6: f(0) = 2.67, f(120) ~ 0.75, f(180) = 1.33); w = omega/M.')
p('=> coefficient of w^2 ln(w) in delta_V(lambda = M): a(phi) = -(alpha/pi) 4 f(phi)/(1 + cos^2 phi).  Extracted numerically from')
p('   delta_V/w^2 at w = 1e-3 and 2e-3 (difference / ln 2):')
p('| phi | a(phi) numerical | a(phi) BF | ratio |')
p('|---|---|---|---|')
for phi in [0.001, 30, 60, 90, 120, 150, 179.999]:
    w1, w2 = 1e-3 * Mp, 2e-3 * Mp
    d1 = rc.delta_virtual(w1, phi, lam=Mp) / (w1 / Mp) ** 2
    d2 = rc.delta_virtual(w2, phi, lam=Mp) / (w2 / Mp) ** 2
    a_num = (d2 - d1) / np.log(2)
    c = np.cos(np.radians(phi)); f = 1 + c + c ** 2 - c ** 3 / 3
    a_bf = -(rc.ALPHA / np.pi) * 4 * f / (1 + c ** 2)
    p('| %g | %.5e | %.5e | %.4f |' % (phi, a_num, a_bf, a_num / a_bf))
p()
p('Coefficient of ln(Delta E) (soft part), proton 100 MeV: exact 2(2y coth 2y - 1)(alpha/pi) [= BF (39) and (57)] vs NR dipole (4/3)(alpha/pi) T/M:')
k = rc.kin(100., 90.); T = float(k['Ep_lab'] - k['M'])
y = mp.asinh(mp.sqrt(T / (2 * Mp)))
p('  numerical d(delta)/d ln(Delta E) = %.6e ; exact = %.6e ; NR = %.6e' % (
    (rc.soft_lab(100., 90., 6.0, lam=1.) - rc.soft_lab(100., 90., 3.0, lam=1.)) / np.log(2),
    float(rc.ALPHA / mp.pi * 2 * (2 * y * mp.coth(2 * y) - 1)), 4 / 3 * rc.ALPHA / np.pi * T / Mp))
p()
p('## 7. Soft factor: lab-frame closed form (tHooft-Veltman/Denner) vs Brown-Feynman Eq. (39) vs brute-force integral; CM vs DD Eq. (4.1)')


def bf39(w, th, dE, M, lam):
    k = rc.kin(w, th, M); om, omp = k['omega'], k['omp']
    kap = -2 * om / M; tau = 2 * omp / M
    y = mp.asinh(mp.sqrt(-(kap + tau) / 4))
    h = lambda z: mp.quad(lambda u: u * mp.coth(u), [0, z]) / z
    val = 2 * (1 - 2 * y * mp.coth(2 * y)) * (mp.log(2 * mp.mpf(dE) / lam) - mp.mpf(1) / 2) + 4 * y * mp.coth(2 * y) * (h(2 * y) - 1)
    return float(-rc.ALPHA / mp.pi * val)


p('| omega | theta | M | Delta E | lambda | tHV (lab) | BF (39) | numeric (lab) |')
p('|---|---|---|---|---|---|---|---|')
