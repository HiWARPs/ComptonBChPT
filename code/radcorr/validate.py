for th in [1e-4, 1e-3, 1e-2, 0.1, 1, 179, 179.9, 179.99, 179.999, 180 - 1e-4]:
    p('| %g | %.8e |' % (th, rc.delta(150., th, 3.0)))
p()
# ---------------------------------------------------------------- table of delta
p('## 9. Table of delta [%] for the proton (lab), Delta E = soft-photon cut in the lab')
omegas = [60, 80, 100, 120, 140, 150]; thetas = [0, 45, 90, 135, 180]
tab = rc.table(omegas, thetas, (1.0, 3.0, 10.0, '3%'))
rows = []
for dE in [1.0, 3.0, 10.0, '3%']:
    p()
    p('Delta E = %s%s' % (dE, '' if dE == '3%' else ' MeV'))
    p('| omega \\ theta | ' + ' | '.join('%g' % t for t in thetas) + ' |')
    p('|---|' + '---|' * len(thetas))
    for i, w in enumerate(omegas):
        p('| %g | ' % w + ' | '.join('%+.4f' % tab[dE][i, j] for j in range(len(thetas))) + ' |')
        for j, t in enumerate(thetas):
            rows.append((dE, w, t, tab[dE][i, j]))
p()
p('Virtual part alone (lambda = M, i.e. the lambda-independent part in the convention ln(lambda/M) = 0) and the ln(Delta E) slope [% per unit ln Delta E]:')
p('| omega \\ theta | ' + ' | '.join('%g' % t for t in thetas) + ' |')
p('|---|' + '---|' * len(thetas))
for w in omegas:
    p('| %g | ' % w + ' | '.join('%+.4f / %.4f' % (100 * rc.delta_virtual_only(w, t, lam=Mp),
                                                    0 if t == 0 else 100 * (rc.soft_lab(w, min(t, 180 - 1e-4), 2.0, lam=Mp) - rc.soft_lab(w, min(t, 180 - 1e-4), 1.0, lam=Mp)) / np.log(2))
                                 for t in thetas) + ' |')
with open(os.path.join(OUT, 'delta_table.csv'), 'w') as f:
    f.write('dE,omega_MeV,theta_lab_deg,delta_percent\n')
    for r in rows:
        f.write('%s,%g,%g,%.6e\n' % r)
p()
