for w in [60, 100, 150]:
    for th in [45, 90, 135]:
        s0 = rc.sigma3(w, th); s1 = rc.sigma3(w, th, order=1)
        p('| %g | %g | %+.4f | %+.4f | %+.4f | %.5f | %.5f | %+.2e | %+.2e |' % (
            w, th, 100 * rc.delta(w, th, 3.0), 100 * rc.delta(w, th, 3.0, pol='par'), 100 * rc.delta(w, th, 3.0, pol='perp'),
            s0, s1, s1 - s0, (s1 - s0) / s0))
