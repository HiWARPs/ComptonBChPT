SUBROUTINE zsolve3(A,b)
  ! Gaussian elimination with partial pivoting, b <- A^-1 b
  IMPLICIT NONE
  COMPLEX*16, INTENT(inout) :: A(3,3), b(3)
  COMPLEX*16 f, tmp(3)
  INTEGER i, j, k, p
  DO k=1,3
     p=k
     DO i=k+1,3
        IF(ABS(A(i,k)).GT.ABS(A(p,k))) p=i
     ENDDO
     IF(p.NE.k) THEN
        tmp=A(k,:); A(k,:)=A(p,:); A(p,:)=tmp
        f=b(k); b(k)=b(p); b(p)=f
     ENDIF
     DO i=k+1,3
        f=A(i,k)/A(k,k)
        A(i,k:3)=A(i,k:3)-f*A(k,k:3)
        b(i)=b(i)-f*b(k)
     ENDDO
  ENDDO
  DO k=3,1,-1
     b(k)=(b(k)-SUM(A(k,k+1:3)*b(k+1:3)))/A(k,k)
  ENDDO
END SUBROUTINE zsolve3

